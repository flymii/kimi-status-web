#!/usr/bin/env node
// Build userscript/kimi-status-web.user.js from web/overlay.js + web/overlay.css,
// so the status bar keeps a single source of truth.
//
//   node scripts/build-userscript.mjs                 # default server port 8710
//   node scripts/build-userscript.mjs --port 8712     # different server port

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function argValue(flag, fallback) {
  const index = process.argv.indexOf(flag);
  return index >= 0 && process.argv[index + 1] ? process.argv[index + 1] : fallback;
}

const port = argValue('--port', '8710');
const base = argValue('--base', `http://127.0.0.1:${port}/_kimi-status`);
const version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version;
const overlay = fs.readFileSync(path.join(root, 'web', 'overlay.js'), 'utf8');
const css = fs.readFileSync(path.join(root, 'web', 'overlay.css'), 'utf8');

const header = `// ==UserScript==
// @name         Kimi Status Web · kimi web 状态条
// @name:en      Kimi Status Web
// @namespace    kimi-status-web
// @version      ${version}
// @description  在 kimi web 的消息输入框下面显示实时指标：入/出 token、缓存命中率、tok/s、首字延迟
// @description:en Live tokens, cache hit rate, throughput and TTFT inside the Kimi Code web UI
// @author       kimi-status-web
// @match        http://127.0.0.1/*
// @match        http://localhost/*
// @run-at       document-idle
// @grant        none
// @noframes
// ==/UserScript==

// Generated by scripts/build-userscript.mjs — edit web/overlay.js / web/overlay.css instead.
// 指标来自本机 kimi-status-web 服务（默认 http://127.0.0.1:${port}/）；
// 换端口就改下面这行，或用 node scripts/build-userscript.mjs --port <port> 重新生成。
window.__KIMI_STATUS_BASE = ${JSON.stringify(base)};
window.__KIMI_STATUS_CSS = ${JSON.stringify(css)};
`;

const out = `${header}\n${overlay}`;
const target = path.join(root, 'userscript', 'kimi-status-web.user.js');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
process.stdout.write(
  `wrote userscript/kimi-status-web.user.js (${out.length} bytes, base ${base})\n`,
);
